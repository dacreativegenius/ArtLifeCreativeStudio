import { COLOR_SLOTS } from "./schema";
import type { FontSpec, RadiusScale, SpacingScale, TypeSpec } from "./parse";

export interface EmitCssInput {
  /** Semantic color tokens: slot -> bare HSL tuple `"H S% L%"`. */
  colors: Record<string, string>;
  /** Border radius, e.g. `"0.5rem"`. */
  radius: string;
  /** Full named spacing scale persisted by the design-system schema. */
  spacing: SpacingScale;
  /** Full named radius scale persisted by the design-system schema. */
  radii: RadiusScale;
  /** Font families for the sans/serif/mono theme keys. */
  font: FontSpec;
  /** Required typography scale + weights. */
  type: TypeSpec;
}

