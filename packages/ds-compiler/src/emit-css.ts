/**
 * Emit the Tailwind v4 global.css from already-resolved tokens.
 *
 * Output shape mirrors apps/vite/client/global.css: imports, @source, the
 * class-based dark variant, :root, @theme inline (colors, radius scale, fonts,
 * spacing, optional type scale/weights, animations), the four @keyframes, and
 * the @layer base block.
 * Every color value is hsl()-wrapped so the file never contains a raw hex.
 */
export function emitCss({
  colors,
  radius,
  spacing,
  radii,
  font,
  type,
}: EmitCssInput): string {
  const authoredSlots = COLOR_SLOTS.filter((slot) => colors[slot] !== undefined);
  const rootVars = authoredSlots.map(
    (slot) => `  --${slot}: hsl(${colors[slot]});`,
  ).join("\n");

  const themeColors = authoredSlots.map(
    (slot) => `  --color-${slot}: var(--${slot});`,
  ).join("\n");

  const quoteCssFamily = (family: string): string =>
    `"${family.replace(/"/g, '\\"')}"`;

  const fontReferenceVars = Object.keys(font)
    .sort()
    .map((key) => `  --ds-font-${key}: ${quoteCssFamily(font[key].cssFamilyName)}, ${font[key].fallback};`)
    .join("\n");

  const typeVars = Object.keys(type.scale)
    .sort()
    .flatMap((key) => {
      const step = type.scale[key];
      return [
        `  --text-${key}: ${step.fontSize};`,
        `  --text-${key}--line-height: ${step.lineHeight};`,
        ...(step.letterSpacing
          ? [`  --text-${key}--letter-spacing: ${step.letterSpacing};`]
          : []),
        `  --font-${key}: var(--ds-font-${step.fontKey});`,
        ...(step.fontStyle
          ? [`  --font-style-${key}: ${step.fontStyle};`]
          : []),
      ];
    })
    .join("\n");

  const weightVars = Object.keys(type.weights)
    .sort()
    .map((key) => `  --font-weight-${key}: ${type.weights[key]};`)
    .join("\n");

  const spacingRootVars = Object.keys(spacing)
    .sort()
    .map((key) => `  --ds-space-${key}: ${spacing[key as keyof SpacingScale]};`)
    .join("\n");

  // Tailwind v4 reserves the --spacing-* namespace for every spacing-derived
  // utility, including max-w-*, size-*, padding, margin, and gap. Prefix the
  // authored rhythm scale so `max-w-xl` keeps Tailwind's normal 36rem meaning
  // while authored rhythm remains available as p-ds-xl, gap-ds-md, and so on.
  const spacingThemeVars = Object.keys(spacing)
    .sort()
    .map((key) => `  --spacing-ds-${key}: var(--ds-space-${key});`)
    .join("\n");

  const radiusVars = Object.keys(radii)
    .sort()
    .map((key) => `  --radius-${key}: ${radii[key as keyof RadiusScale]};`)
    .join("\n");

  const typeBlock = typeVars ? `\n\n${typeVars}` : "";
  const defaultFontBlock = type.scale.body
    ? "\n\n  --font-sans: var(--font-body);"
    : "";
  const weightBlock = weightVars ? `\n\n${weightVars}` : "";
  const typeUtilities = Object.keys(type.scale)
    .sort()
    .map((key) => {
      const step = type.scale[key];
      const weight = type.weights[key];
      return `  .type-${key} {
    font-family: var(--font-${key});
    font-size: var(--text-${key});
    line-height: var(--text-${key}--line-height);${step.letterSpacing ? `\n    letter-spacing: var(--text-${key}--letter-spacing);` : ""}${step.fontStyle ? `\n    font-style: var(--font-style-${key});` : ""}${weight !== undefined ? `\n    font-weight: var(--font-weight-${key});` : ""}
  }`;
    })
    .join("\n");
  // Components layer, after the recipes: a role class overrides `ds-*` recipe
  // typography, and any Tailwind utility on the same element (`text-7xl`,
  // `font-black`, a panel edit) overrides the role — Tailwind orders
  // `components` below `utilities` regardless of source order.
  const typeUtilitiesBlock = typeUtilities
    ? `\n@layer components {\n${typeUtilities}\n}`
    : "";

  return `${HEADER}
@import 'tailwindcss';
@import 'tw-animate-css';

/* v4 scans source text, not the module graph. The CSS file lives at
   apps/vite/client/global.css (client/ -> vite/ -> apps/ -> root), so
   packages/ui/src is three levels up. Without this, @vibe/ui classes drop. */
@source '../../../packages/ui/src';
@custom-variant dark (&:is(.dark *));
:root {
${rootVars}
  --radius: ${radius};
${spacingRootVars}
${fontReferenceVars ? `\n${fontReferenceVars}` : ""}
}
@theme inline {
${themeColors}

${radiusVars}

${spacingThemeVars}${typeBlock}${defaultFontBlock}${weightBlock}

  --animate-accordion-down: accordion-down 0.2s ease-out;
  --animate-accordion-up: accordion-up 0.2s ease-out;
  --animate-fade-in: fade-in 0.4s ease-out;
  --animate-shimmer: shimmer 2s linear infinite;
}

@keyframes accordion-down {
  from { height: 0; }
  to { height: var(--radix-accordion-content-height); }
}
@keyframes accordion-up {
  from { height: var(--radix-accordion-content-height); }
  to { height: 0; }
}
@keyframes fade-in {
  from { opacity: 0; transform: translateY(8px); }
  to { opacity: 1; transform: translateY(0); }
}
@keyframes shimmer {
  from { background-position: 0 0; }
  to { background-position: -200% 0; }
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground;
    font-feature-settings: "rlig" 1, "calt" 1;
  }
}
${COMPONENT_RECIPES_CSS}
${typeUtilitiesBlock}
`;
}
